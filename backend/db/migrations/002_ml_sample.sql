-- Additive support for the explicitly requested 100-product shared-catalog import.
CREATE TABLE analysis_runs (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 run_key text NOT NULL UNIQUE,
 source_sha256 char(64) NOT NULL,
 selection_sha256 char(64) NOT NULL,
 manifest_json jsonb NOT NULL,
 scored_at timestamptz NOT NULL,
 imported_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE products ADD COLUMN source_system varchar(50), ADD COLUMN source_product_id varchar(100);
CREATE INDEX products_source ON products(source_system, source_product_id);
ALTER TABLE product_analyses
 ADD COLUMN run_id bigint REFERENCES analysis_runs(id) ON DELETE RESTRICT,
 ADD COLUMN status_schema_version text NOT NULL DEFAULT 'legacy_v1',
 ADD COLUMN status_reason text,
 ADD COLUMN product_type text,
 ADD COLUMN taxonomy_version text,
 ADD COLUMN scored_at timestamptz,
 ADD COLUMN prediction_lower numeric(20,4) CHECK (prediction_lower>=0),
 ADD COLUMN prediction_upper numeric(20,4) CHECK (prediction_upper>=0),
 ADD CONSTRAINT analyses_interval CHECK (prediction_lower<=prediction_upper),
 ADD CONSTRAINT analyses_run_product UNIQUE(run_id,product_id);
ALTER TABLE product_analyses DROP CONSTRAINT product_analyses_status_check;
ALTER TABLE product_analyses ADD CONSTRAINT product_analyses_status_check CHECK (
 (status_schema_version='legacy_v1' AND status IN (
 'positive_feedback_below_reference','low_rating_below_reference','at_or_above_reference',
 'zero_sales_needs_investigation','zero_sales_no_priority_signal','below_reference_insufficient_reviews',
 'monitor_gap','undecided','insufficient_basis')) OR
 (status_schema_version='ml_v2' AND status IN (
 'positive_feedback_low_sales','low_rating_low_sales','performing_well',
 'untapped_potential','difficult_to_sell','insufficient_data'))
);
ALTER TABLE improvement_actions
 ADD COLUMN origin text NOT NULL DEFAULT 'legacy' CHECK (origin IN ('legacy','manual','ml_rule')),
 ADD COLUMN rule_id text;
ALTER TABLE improvement_actions DROP CONSTRAINT improvement_actions_type_check;
ALTER TABLE improvement_actions ADD CONSTRAINT improvement_actions_type_check CHECK (type IN (
 'review_price','complete_description','review_images_or_video','review_images','review_video',
 'inspect_reviews','verify_listing_and_stock','verify_exposure','other'));
ALTER TABLE improvement_actions ADD CONSTRAINT ml_rule_required CHECK (origin<>'ml_rule' OR (rule_id IS NOT NULL AND length(trim(rule_id))>0));
CREATE UNIQUE INDEX actions_ml_rule ON improvement_actions(analysis_id,rule_id) WHERE origin='ml_rule';
CREATE OR REPLACE FUNCTION sellens_keep_original_suggestion() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.original_suggestion_json IS DISTINCT FROM OLD.original_suggestion_json
 OR NEW.analysis_id IS DISTINCT FROM OLD.analysis_id
 OR NEW.origin IS DISTINCT FROM OLD.origin OR NEW.rule_id IS DISTINCT FROM OLD.rule_id
 OR (OLD.origin='ml_rule' AND NEW.type IS DISTINCT FROM OLD.type) THEN
  RAISE EXCEPTION 'Original suggestion and analysis relation are immutable';
 END IF;
 RETURN NEW;
END $$;
