CREATE TABLE users (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 full_name varchar(150) NOT NULL CHECK (length(trim(full_name))>0),
 email varchar(254) NOT NULL UNIQUE,
 password_hash varchar(255) NOT NULL,
 role varchar(16) NOT NULL DEFAULT 'reviewer' CHECK (role IN ('admin','reviewer')),
 is_active boolean NOT NULL DEFAULT true,
 created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX users_email_normalized ON users(lower(email));
CREATE TABLE categories (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 code varchar(80) NOT NULL UNIQUE, name varchar(150) NOT NULL, description text
);
CREATE TABLE products (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 category_id bigint REFERENCES categories(id) ON DELETE RESTRICT,
 name varchar(500) NOT NULL CHECK (length(trim(name))>0), description text, brand varchar(255),
 product_url text, thumbnail_url text, currency char(3) NOT NULL DEFAULT 'VND',
 price numeric(18,2) CHECK (price>=0), original_price numeric(18,2) CHECK (original_price>=0),
 quantity_sold bigint CHECK (quantity_sold>=0), rating_average numeric(3,2) CHECK (rating_average BETWEEN 0 AND 5),
 review_count integer CHECK (review_count>=0), number_of_images integer CHECK (number_of_images>=0), has_video boolean,
 sales_scope varchar(20) NOT NULL DEFAULT 'unknown' CHECK (sales_scope IN ('unknown','listing','product_page')),
 sales_label_verified boolean NOT NULL DEFAULT false, source_data_json jsonb, observed_at timestamptz,
 imported_by bigint REFERENCES users(id) ON DELETE RESTRICT,
 created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX products_category ON products(category_id);
CREATE TABLE product_analyses (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 product_id bigint NOT NULL REFERENCES products(id) ON DELETE RESTRICT,
 analyzed_by bigint REFERENCES users(id) ON DELETE RESTRICT,
 reference_sold numeric(20,4) CHECK (reference_sold>=0), probability_positive_sales numeric(7,6) CHECK (probability_positive_sales BETWEEN 0 AND 1),
 sales_gap numeric(20,4), status varchar(60) NOT NULL DEFAULT 'insufficient_basis' CHECK (status IN (
 'positive_feedback_below_reference','low_rating_below_reference','at_or_above_reference',
 'zero_sales_needs_investigation','zero_sales_no_priority_signal','below_reference_insufficient_reviews',
 'monitor_gap','undecided','insufficient_basis')),
 is_eligible boolean NOT NULL DEFAULT false, needs_review boolean NOT NULL DEFAULT false,
 priority_score numeric(12,6), model_version varchar(100), pipeline_version varchar(100) NOT NULL,
 input_snapshot_json jsonb NOT NULL, comparison_json jsonb, evidence_json jsonb, config_json jsonb NOT NULL,
 limitation_note text, analyzed_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX analyses_product_time ON product_analyses(product_id,analyzed_at);
CREATE INDEX analyses_status_review ON product_analyses(status,needs_review);
CREATE TABLE improvement_actions (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 analysis_id bigint NOT NULL REFERENCES product_analyses(id) ON DELETE RESTRICT,
 type varchar(40) NOT NULL CHECK (type IN ('review_price','complete_description','review_images_or_video','inspect_reviews','verify_listing_and_stock','verify_exposure','other')),
 title varchar(255) NOT NULL, description text, original_suggestion_json jsonb NOT NULL, information_needed text,
 status varchar(20) NOT NULL DEFAULT 'proposed' CHECK (status IN ('proposed','accepted','in_progress','completed','rejected','cancelled')),
 assigned_to bigint REFERENCES users(id) ON DELETE RESTRICT, created_by bigint REFERENCES users(id) ON DELETE RESTRICT,
 decision_reason text, due_at timestamptz, completed_at timestamptz, outcome_note text,
 created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
 CHECK (status<>'rejected' OR length(trim(decision_reason))>0)
);
CREATE INDEX actions_analysis ON improvement_actions(analysis_id);
CREATE INDEX actions_assignee_status ON improvement_actions(assigned_to,status);
CREATE TABLE action_history (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 action_id bigint NOT NULL REFERENCES improvement_actions(id) ON DELETE RESTRICT,
 changed_by bigint REFERENCES users(id) ON DELETE RESTRICT, event_type varchar(50) NOT NULL,
 before_json jsonb, after_json jsonb, comment text, created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX history_action_time ON action_history(action_id,created_at);
-- Auxiliary operational tables, separate from the six domain entities.
CREATE TABLE sellens_sessions (
 token_hash char(64) PRIMARY KEY, user_id bigint NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
 expires_at timestamptz NOT NULL, created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX sessions_user ON sellens_sessions(user_id);
CREATE TABLE sellens_login_limits (key char(64) PRIMARY KEY, attempts integer NOT NULL, window_start timestamptz NOT NULL);
CREATE TABLE sellens_seed_records (
 seed_key text PRIMARY KEY, entity text NOT NULL, record_id bigint NOT NULL
);
-- Historical analyses and audit events are immutable even through accidental SQL updates.
CREATE FUNCTION sellens_reject_history_mutation() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'Historical records are append only'; END $$;
CREATE TRIGGER immutable_analyses BEFORE UPDATE OR DELETE ON product_analyses FOR EACH ROW EXECUTE FUNCTION sellens_reject_history_mutation();
CREATE TRIGGER immutable_history BEFORE UPDATE OR DELETE ON action_history FOR EACH ROW EXECUTE FUNCTION sellens_reject_history_mutation();
CREATE FUNCTION sellens_keep_original_suggestion() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.original_suggestion_json IS DISTINCT FROM OLD.original_suggestion_json OR NEW.analysis_id IS DISTINCT FROM OLD.analysis_id THEN
  RAISE EXCEPTION 'Original suggestion and analysis relation are immutable';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER immutable_original BEFORE UPDATE ON improvement_actions FOR EACH ROW EXECUTE FUNCTION sellens_keep_original_suggestion();
