-- One regular account owns exactly one store. Existing catalog explicitly goes to user1.
CREATE TABLE stores (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 owner_user_id bigint NOT NULL UNIQUE REFERENCES users(id) ON DELETE RESTRICT,
 name varchar(200) NOT NULL CHECK(length(trim(name))>0),
 is_active boolean NOT NULL DEFAULT true,
 created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now()
);
LOCK TABLE users, products IN SHARE ROW EXCLUSIVE MODE;
DO $$
DECLARE legacy_owner bigint;
BEGIN
 SELECT id INTO STRICT legacy_owner FROM users
 WHERE lower(email)=lower(current_setting('sellens.legacy_owner_email',true)) AND role='reviewer' AND is_active;
 INSERT INTO stores(owner_user_id,name)
 SELECT id,CASE WHEN id=legacy_owner THEN 'J4F store' ELSE full_name || ' store' END
 FROM users WHERE role='reviewer';
END $$;
ALTER TABLE products ADD COLUMN store_id bigint REFERENCES stores(id) ON DELETE RESTRICT;
UPDATE products SET store_id=(SELECT s.id FROM stores s JOIN users u ON u.id=s.owner_user_id
 WHERE lower(u.email)=lower(current_setting('sellens.legacy_owner_email',true)));
ALTER TABLE products ALTER COLUMN store_id SET NOT NULL;
CREATE INDEX products_store_category ON products(store_id,category_id);
CREATE FUNCTION sellens_auto_store() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.role='reviewer' THEN
  INSERT INTO stores(owner_user_id,name) VALUES(NEW.id,NEW.full_name || ' store') ON CONFLICT(owner_user_id) DO NOTHING;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER user_store AFTER INSERT OR UPDATE OF role ON users FOR EACH ROW EXECUTE FUNCTION sellens_auto_store();
CREATE FUNCTION sellens_keep_store_owner() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF (TG_TABLE_NAME='stores' AND to_jsonb(NEW)->'owner_user_id' IS DISTINCT FROM to_jsonb(OLD)->'owner_user_id')
 OR (TG_TABLE_NAME='products' AND to_jsonb(NEW)->'store_id' IS DISTINCT FROM to_jsonb(OLD)->'store_id') THEN
  RAISE EXCEPTION 'Store ownership and product store cannot be reassigned';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER immutable_store_owner BEFORE UPDATE ON stores FOR EACH ROW EXECUTE FUNCTION sellens_keep_store_owner();
CREATE TRIGGER immutable_product_store BEFORE UPDATE ON products FOR EACH ROW EXECUTE FUNCTION sellens_keep_store_owner();
