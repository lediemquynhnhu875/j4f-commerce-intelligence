-- PROPOSAL ONLY. Not applied, and not run by the current npm run db:migrate.
-- Run once in the Neon SQL Editor against the database containing migration 001.
-- Existing users/products/analyses/actions/history are preserved.
-- Stage 1 deliberately permits NULL products.store_id for unassigned legacy rows.
BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '30s';

CREATE TABLE public.stores (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_user_id bigint NOT NULL REFERENCES public.users(id) ON DELETE RESTRICT,
    name varchar(200) NOT NULL CHECK (length(trim(name)) > 0),
    description text,
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX stores_owner_active ON public.stores(owner_user_id, is_active);

ALTER TABLE public.products
    ADD COLUMN store_id bigint REFERENCES public.stores(id) ON DELETE RESTRICT;
CREATE INDEX products_store_category ON public.products(store_id, category_id);

-- A category is shared reference metadata; store membership belongs to the listing.
COMMENT ON COLUMN public.stores.owner_user_id IS
    'Application owner. One account may own multiple stores; source seller metadata does not establish ownership.';
COMMENT ON COLUMN public.products.store_id IS
    'One store per application listing. NULL only for legacy records awaiting explicit assignment.';

-- After the initial legacy assignment, ownership stays stable for saved history.
-- Moving a listing/transferring a store requires a separate reviewed workflow.
CREATE FUNCTION public.sellens_keep_product_store() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF OLD.store_id IS NOT NULL AND NEW.store_id IS DISTINCT FROM OLD.store_id THEN
        RAISE EXCEPTION 'Assigned product store cannot be changed; create a new store listing instead';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER immutable_product_store
    BEFORE UPDATE OF store_id ON public.products
    FOR EACH ROW EXECUTE FUNCTION public.sellens_keep_product_store();

CREATE FUNCTION public.sellens_keep_store_owner() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.owner_user_id IS DISTINCT FROM OLD.owner_user_id THEN
        RAISE EXCEPTION 'Store owner transfer requires a separate reviewed workflow';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER immutable_store_owner
    BEFORE UPDATE OF owner_user_id ON public.stores
    FOR EACH ROW EXECUTE FUNCTION public.sellens_keep_store_owner();

COMMIT;

